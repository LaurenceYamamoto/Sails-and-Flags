import fs from 'node:fs';
import * as OpenCC from 'opencc-js';
import {catalog} from '../src/i18n.js';

// Build-time conversion only; no conversion library/dictionary is shipped to the browser.
// Explicit city spellings are reviewed separately in city-names.js.
const convert=OpenCC.Converter({from:'cn',to:'tw'});
const result=Object.fromEntries(Object.entries(catalog).map(([key,row])=>[key,convert(row[0])]));
// 吁 in the historical dynasty name is not the verb 呼籲.
result['Toungoo Burma']='東吁王朝緬甸';
const source='// Generated by npm run build:translations from reviewed Simplified Chinese strings.\nexport const traditionalTranslations = '+JSON.stringify(result,null,2)+';\n';
if(process.argv.includes('--check')){
 if(fs.readFileSync('src/translation-traditional.js','utf8')!==source)throw Error('Traditional Chinese catalog is stale. Run npm run build:translations.');
}else fs.writeFileSync('src/translation-traditional.js',source);
console.log(`Traditional Chinese: ${Object.keys(result).length} entries`);
